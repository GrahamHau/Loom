const allSources = [...sources, ...disabled];
const current = listNewsSources();
let added = 0;
let updated = 0;

for (const source of allSources) {
  const existing = current.find((item) => item.id === source.id || item.url === source.url);
  if (existing) {
    updateNewsSource(existing.id, { ...source, last_error: source.last_error ?? existing.last_error });
    updated += 1;
  } else {
    createNewsSource(source);
    added += 1;
  }
}

